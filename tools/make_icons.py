def rows(art):
    r = [l for l in art.strip("\n").split("\n")]
    assert len(r) == 32 and all(len(l) == 32 for l in r), [len(l) for l in r]
    return r
def mask(r):
    # fill each row between its first and last set pixel (solid silhouette)
    out = []
    for l in r:
        if "#" in l:
            a, b = l.index("#"), l.rindex("#")
            out.append("." * a + "#" * (b - a + 1) + "." * (31 - b))
        else:
            out.append("." * 32)
    return out
def hexrows(r):
    return " ".join("%08X" % int(l.replace("#", "1").replace(".", "0"), 2) for l in r)
def icn(rid, name, art):
    r = rows(art)
    return 'resource \'ICN#\' (%d, "%s", purgeable) {\n\t{\t/* array: 2 elements */\n\t\t$"%s",\n\t\t$"%s"\n\t}\n};\n' % (
        rid, name, hexrows(r), hexrows(mask(r)))
out = "/* generated by tools/make_icons.py - do not edit */\n\n" + icn(128, "WordReader", APP) + "\n" + icn(129, "Word document", DOC)
open(os.path.join(os.path.dirname(__file__), "..", "src", "icons.r"), "w").write(out)
